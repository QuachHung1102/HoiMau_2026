// Copies what the move demos need out of design/ into the app (Task 36):
//   src/assets/motion/exercises.json   both rigs as element trees + every `kind: "exercise"` entry of the catalog
//   src/assets/motion/poses/<id>.png   the key pose of each entry (design/motion/exercises/<id>.png)
//   src/assets/motion/poses.ts         the static require() of each pose (Metro needs literal paths)
// node scripts/extract-exercise-motion.mjs           write them
// node scripts/extract-exercise-motion.mjs --check   exit 1 when the committed files differ from a fresh extraction
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => path.join(root, ...parts);
const FIELDS = ['rig', 'demo', 'durationToken', 'prop', 'poster', 'pattern', 'highlight', 'tracks'];

const camel = name => name.replace(/-([a-z])/g, (_m, c) => c.toUpperCase());

/** The rig SVG as a tree: {tag, id?, origin?, attrs, children}. The SVGs are flat, hand-written markup. */
function parseSvg(text) {
  const top = { children: [] };
  const stack = [top];
  for (const [, close, tag, rawAttrs, selfClose] of text.matchAll(/<(\/?)([a-z]+)([^>]*?)(\/?)>/g)) {
    if (close) {
      stack.pop();
      continue;
    }
    const node = { tag, attrs: {}, children: [] };
    for (const [, name, value] of rawAttrs.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
      if (name === 'id') node.id = value;
      else if (name === 'style') {
        const origin = /transform-origin:\s*([-\d.]+)px\s+([-\d.]+)px/.exec(value);
        if (!origin || value.replace(origin[0], '').replace(/[;\s]/g, '')) throw new Error(`unsupported style "${value}"`);
        node.origin = [Number(origin[1]), Number(origin[2])];
      } else if (tag === 'svg') {
        if (name === 'viewBox') node.attrs.viewBox = value;
      } else node.attrs[camel(name)] = value;
    }
    stack.at(-1).children.push(node);
    if (!selfClose) stack.push(node);
  }
  if (stack.length !== 1 || top.children.length !== 1) throw new Error('unbalanced svg');
  return top.children[0];
}

function extract() {
  const catalog = JSON.parse(fs.readFileSync(at('design/motion/catalog.json'), 'utf8'));
  const exercises = catalog.filter(entry => entry.kind === 'exercise');
  const rigs = Object.fromEntries(['side', 'front'].map(name => [name, parseSvg(fs.readFileSync(at(`design/assets/exercise/rig-${name}.svg`), 'utf8'))]));
  const moves = Object.fromEntries(
    exercises.map(entry => [entry.id, Object.fromEntries(FIELDS.filter(field => entry[field] !== undefined).map(field => [field, entry[field]]))]),
  );
  const files = new Map();
  files.set('src/assets/motion/exercises.json', `${JSON.stringify({ rigs, moves }, null, 1)}\n`);
  files.set(
    'src/assets/motion/poses.ts',
    [
      '// Generated by scripts/extract-exercise-motion.mjs; do not edit.',
      "import type { ImageSourcePropType } from 'react-native';",
      '',
      '/** The key pose of each exercise demo (the pose at its `poster` time), by catalog id. */',
      'export const poses: Record<string, ImageSourcePropType> = {',
      ...exercises.map(entry => `  '${entry.id}': require('./poses/${entry.id}.png'),`),
      '};',
      '',
    ].join('\n'),
  );
  for (const entry of exercises) files.set(`src/assets/motion/poses/${entry.id}.png`, fs.readFileSync(at(`design/motion/exercises/${entry.id}.png`)));
  return files;
}

const files = extract();
const same = (file, want) => {
  if (!fs.existsSync(at(file))) return false;
  const have = fs.readFileSync(at(file));
  // Text files may be checked out with CRLF (core.autocrlf); git stores them with LF.
  return typeof want === 'string' ? have.toString('utf8').replace(/\r\n/g, '\n') === want : have.equals(want);
};
if (process.argv.includes('--check')) {
  const stale = [...files].filter(([file, want]) => !same(file, want)).map(([file]) => file);
  const extra = fs.existsSync(at('src/assets/motion/poses'))
    ? fs.readdirSync(at('src/assets/motion/poses')).map(name => `src/assets/motion/poses/${name}`).filter(file => !files.has(file))
    : [];
  if (stale.length || extra.length) {
    console.error(`Exercise motion is out of date; run node scripts/extract-exercise-motion.mjs\n${[...stale.map(f => `differs: ${f}`), ...extra.map(f => `not in the catalog: ${f}`)].join('\n')}`);
    process.exit(1);
  }
  console.log(`OK: ${files.size} files match design/`);
} else {
  fs.mkdirSync(at('src/assets/motion/poses'), { recursive: true });
  for (const [file, content] of files) if (!same(file, content)) fs.writeFileSync(at(file), content);
  console.log(`wrote ${files.size} files`);
}
